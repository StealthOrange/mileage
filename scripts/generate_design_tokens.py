#!/usr/bin/env python3
"""Generate native and browser design constants from the same source."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def kebab(name):
    return re.sub(r"(?<!^)([A-Z])", r"-\1", name).lower()


def generate():
    tokens = json.loads((ROOT / "design/tokens.json").read_text())
    swift = ["// Generated by scripts/generate_design_tokens.py. Edit design/tokens.json.",
             "import CoreGraphics", "", "enum MileageTokens {"]
    for mode, colors in tokens["colors"].items():
        swift.append(f"    enum {mode.title()} {{")
        for name, value in colors.items():
            if not re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
                raise ValueError(f"Invalid color: {name}")
            swift.append(f"        static let {name} = 0x{value[1:]}")
        swift.append("    }")
    for category in ("space", "radius", "type"):
        swift_name = "Typography" if category == "type" else category.title()
        swift.append(f"    enum {swift_name} {{")
        for name, value in tokens[category].items():
            swift.append(f"        static let {name}: CGFloat = {value}")
        swift.append("    }")
    swift.append("}")

    def palette(mode, indent="  "):
        return [f"{indent}--color-{kebab(name)}: {value};"
                for name, value in tokens["colors"][mode].items()]

    css = ["/* Generated by scripts/generate_design_tokens.py. Edit design/tokens.json. */",
           ":root {", "  color-scheme: light;"] + palette("light")
    for category in ("space", "radius", "type"):
        css += [f"  --{category}-{kebab(name)}: {value}px;"
                for name, value in tokens[category].items()]
    css += ["}", "@media (prefers-color-scheme: dark) {",
            '  :root:not([data-theme="light"]) {', "    color-scheme: dark;"]
    css += palette("dark", "    ") + ["  }", "}", ':root[data-theme="dark"] {',
                                       "  color-scheme: dark;"]
    css += palette("dark") + ["}"]
    return {ROOT / "App/DesignTokens.swift": "\n".join(swift) + "\n",
            ROOT / "preview/tokens.css": "\n".join(css) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated files are current")
    args = parser.parse_args()
    stale = []
    for path, source in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != source:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(source)
    if stale:
        parser.exit(1, "Regenerate design tokens: " + ", ".join(stale) + "\n")
    print("Design tokens are current." if args.check else "Generated native and browser design tokens.")


if __name__ == "__main__":
    main()
